df['TIMESTAMP'] = df['OPD_DATE'] + df['ACT_TIME']

df['dMETERS'] = df['METERS'].diff()
df['dTIMESTAMP'] = (df['TIMESTAMP'].diff()).dt.total_seconds()

df['SPEED'] = df['dMETERS'] / df['dTIMESTAMP']

df.drop(['OPD_DATE', 'ACT_TIME', 'dMETERS', 'dTIMESTAMP'], axis=1, inplace=True)

max_speed_row = df.loc[df['SPEED'].idxmax()]
max_speed = max_speed_row['SPEED']
