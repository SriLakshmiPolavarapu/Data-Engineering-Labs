import pandas as pd

file_path = '/content/bc_trip259172515_230215.csv'
df = pd.read_csv(file_path)

df['OPD_DATE'] = pd.to_datetime(df['OPD_DATE'], format='%d%b%Y:%H:%M:%S')
df['ACT_TIME'] = pd.to_timedelta(df['ACT_TIME'], unit='s')
df['TIMESTAMP'] = df['OPD_DATE'] + df['ACT_TIME']

df.drop(columns=['OPD_DATE', 'ACT_TIME'], inplace=True)

df['dMETERS'] = df['METERS'].diff()
df['dTIMESTAMP'] = df['TIMESTAMP'].diff().dt.total_seconds()

df['SPEED'] = df.apply(lambda row: row['dMETERS'] / row['dTIMESTAMP'] if row['dTIMESTAMP'] != 0 else None, axis=1)

df.drop(columns=['dMETERS', 'dTIMESTAMP'], inplace=True)

min_speed = df['SPEED'].min()
max_speed = df['SPEED'].max()
avg_speed = df['SPEED'].mean()

print(f"Minimum Speed: {min_speed} meters per second")
print(f"Maximum Speed: {max_speed} meters per second")
print(f"Average Speed: {avg_speed} meters per second")

import pandas as pd

df = pd.read_csv('/content/bc_veh4223_230215.csv')

