# 1.

date_columns = [col for col in cases_df.columns if col not in ['countyFIPS', 'County Name', 'State', 'StateFIPS']]

cases_df['Cases'] = cases_df[date_columns].sum(axis=1)
deaths_df['Deaths'] = deaths_df[date_columns].sum(axis=1)

cases_df = cases_df[['countyFIPS', 'County Name', 'State', 'Cases']]
deaths_df = deaths_df[['countyFIPS', 'County Name', 'State', 'Deaths']]

census_df = census_df.rename(columns={
    'County': 'County Name',
    'CountyId': 'countyFIPS'
})

census_df = census_df[['countyFIPS', 'County Name', 'State', 'TotalPop',
                       'IncomePerCap', 'Poverty', 'Unemployment']]

def standardize_name(name):
    return name.lower().replace("county", "").replace("parish", "").strip()

cases_df['County Name'] = cases_df['County Name'].apply(standardize_name)
deaths_df['County Name'] = deaths_df['County Name'].apply(standardize_name)
census_df['County Name'] = census_df['County Name'].apply(standardize_name)

merged_df = cases_df.merge(deaths_df, on=['countyFIPS', 'State'], how='inner')
merged_df = merged_df.merge(census_df, on=['countyFIPS', 'State'], how='inner')

merged_df['CasesPerCap'] = merged_df['Cases'] / merged_df['TotalPop']
merged_df['DeathsPerCap'] = merged_df['Deaths'] / merged_df['TotalPop']

final_df = merged_df[[
    'County Name', 'State', 'Cases', 'Deaths', 'CasesPerCap',
    'DeathsPerCap', 'TotalPop', 'IncomePerCap', 'Poverty', 'Unemployment'
]]

final_df = final_df.dropna(subset=['Cases', 'Deaths', 'TotalPop'])
final_df = final_df.astype({
    'Cases': 'int',
    'Deaths': 'int',
    'TotalPop': 'int',
    'CasesPerCap': 'float',
    'DeathsPerCap': 'float',
    'IncomePerCap': 'float',
    'Poverty': 'float',
    'Unemployment': 'float'
})

final_df.to_csv('integrated_covid_census.csv', index=False)
