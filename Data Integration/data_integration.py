import pandas as pd

cases_df = pd.read_csv('/content/covid_confirmed_usafacts.csv')
deaths_df = pd.read_csv('/content/covid_deaths_usafacts.csv')
census_df = pd.read_csv('/content/acs2017_county_data.csv')

